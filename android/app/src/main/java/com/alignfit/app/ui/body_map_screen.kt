// ─── Body Map Data ────────────────────────────────────────────────────────────

data class BodyRegion(val id: String, val points: List<Offset>, val layer: String = "body") {
    val path: Path by lazy { polygonPath(points) }
}

data class BodyDecoration(val cx: Float, val cy: Float, val rx: Float, val ry: Float)

// A silhouette layer: smooth outline plus the regions clipped to it.
// Side views have a separate "arm" layer drawn over the torso.
data class BodyLayer(val outline: List<Offset>, val regions: List<BodyRegion>) {
    val outlinePath: Path by lazy { polygonPath(outline) }
    val clippedPaths: Map<BodyRegion, Path> by lazy {
        regions.associateWith { Path.combine(PathOperation.Intersect, it.path, outlinePath) }
    }
}

data class BodyMap(
    val viewBoxWidth: Float,
    val viewBoxHeight: Float,
    val layers: List<BodyLayer>,
    val decorations: List<BodyDecoration>
)

private fun polygonPath(points: List<Offset>) = Path().apply {
    moveTo(points.first().x, points.first().y)
    points.drop(1).forEach { lineTo(it.x, it.y) }
    close()
}

enum class BodyMapView(val label: String, val fileName: String) {
    FRONT("정면", "body_front.svg"),
    BACK("후면", "body_back.svg"),
    LEFT("좌측면", "body_left.svg"),
    RIGHT("우측면", "body_right.svg")
}

// ─── SVG Parsing ──────────────────────────────────────────────────────────────

// Parses the SVG assets (generated by android/tools/generate_body_maps.py).
// shape_* polygons are silhouettes; other <polygon>s are selectable regions,
// clipped to shape_body or (data-layer="arm") shape_arm. <ellipse> is the head.
fun loadBodyMap(context: Context, fileName: String): BodyMap {
    context.assets.open("body_maps/$fileName").use { stream ->
        val parser = Xml.newPullParser()
        parser.setInput(stream, "UTF-8")

        var viewBoxWidth = 200f
        var viewBoxHeight = 440f
        val regions = mutableListOf<BodyRegion>()
        val shapes = mutableMapOf<String, List<Offset>>()
        val decorations = mutableListOf<BodyDecoration>()

        var event = parser.eventType
        while (event != XmlPullParser.END_DOCUMENT) {
            if (event == XmlPullParser.START_TAG) {
                when (parser.name) {
                    "svg" -> {
                        parser.getAttributeValue(null, "viewBox")?.let { viewBox ->
                            val parts = viewBox.trim().split(Regex("[\\s,]+"))
                            if (parts.size == 4) {
                                viewBoxWidth = parts[2].toFloatOrNull() ?: viewBoxWidth
                                viewBoxHeight = parts[3].toFloatOrNull() ?: viewBoxHeight
                            }
                        }
                    }
                    "polygon" -> {
                        val id = parser.getAttributeValue(null, "id")
                        val pointsAttr = parser.getAttributeValue(null, "points")
                        if (id != null && pointsAttr != null) {
                            val numbers = pointsAttr.trim()
                                .split(Regex("[\\s,]+"))
                                .mapNotNull { it.toFloatOrNull() }
                            val points = (numbers.indices step 2).mapNotNull { i ->
                                if (i + 1 < numbers.size) Offset(numbers[i], numbers[i + 1]) else null
                            }
                            if (points.size >= 3) {
                                if (id.startsWith("shape_")) {
                                    shapes[id.removePrefix("shape_")] = points
                                } else {
                                    val layer = parser.getAttributeValue(null, "data-layer") ?: "body"
                                    regions.add(BodyRegion(id, points, layer))
                                }
                            }
                        }
                    }
                    "ellipse" -> {
                        val cx = parser.getAttributeValue(null, "cx")?.toFloatOrNull()
                        val cy = parser.getAttributeValue(null, "cy")?.toFloatOrNull()
                        val rx = parser.getAttributeValue(null, "rx")?.toFloatOrNull()
                        val ry = parser.getAttributeValue(null, "ry")?.toFloatOrNull()
                        if (cx != null && cy != null && rx != null && ry != null) {
                            decorations.add(BodyDecoration(cx, cy, rx, ry))
                        }
                    }
                }
            }
            event = parser.next()
        }
        val layers = listOf("body", "arm").mapNotNull { name ->
            shapes[name]?.let { outline -> BodyLayer(outline, regions.filter { it.layer == name }) }
        }
        return BodyMap(viewBoxWidth, viewBoxHeight, layers, decorations)
    }
}

// ─── Hit Testing ──────────────────────────────────────────────────────────────

// Standard ray-casting point-in-polygon test.
private fun polygonContains(points: List<Offset>, x: Float, y: Float): Boolean {
    var inside = false
    var j = points.size - 1
    for (i in points.indices) {
        val pi = points[i]
        val pj = points[j]
        if ((pi.y > y) != (pj.y > y) &&
            x < (pj.x - pi.x) * (y - pi.y) / (pj.y - pi.y) + pi.x
        ) {
            inside = !inside
        }
        j = i
    }
    return inside
}

// ─── Step 2: Body Map Selection ───────────────────────────────────────────────

@OptIn(ExperimentalLayoutApi::class)
@Composable
fun BodyMapSelectionScreen(
    selectedRegions: Set<String>,
    onRegionToggled: (String) -> Unit,
    onNext: () -> Unit,
    onBack: () -> Unit
) {
    val context = LocalContext.current
    val bodyMaps = remember {
        BodyMapView.values().associateWith { view ->
            runCatching { loadBodyMap(context, view.fileName) }.getOrNull()
        }
    }
    var currentView by remember { mutableStateOf(BodyMapView.FRONT) }

    val baseColor = Color(0xFFEDEDED)
    val outlineColor = Color(0xFFC7C7C7)
    val seamColor = Color.White
    val selectedColor = Ink

    Column(modifier = Modifier.fillMaxSize()) {
        SubPageHeader(
            title = "그림에서 짚어 주세요",
            subtitle = "불편한 곳을 탭하면 선택되고, 다시 탭하면 해제돼요.",
            onBack = onBack,
            step = 2
        )

        Column(
            modifier = Modifier
                .weight(1f)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = ScreenPadding)
        ) {
            // Segmented view switcher
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(14.dp))
                    .background(Tint)
                    .padding(4.dp)
            ) {
                BodyMapView.values().forEach { view ->
                    val selected = currentView == view
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .clip(RoundedCornerShape(10.dp))
                            .background(if (selected) Paper else Tint)
                            .clickable { currentView = view }
                            .padding(vertical = 10.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            view.label,
                            fontSize = 13.sp,
                            fontWeight = if (selected) FontWeight.SemiBold else FontWeight.Normal,
                            color = if (selected) Ink else InkSoft
                        )
                    }
                }
            }

            Text(
                text = if (currentView == BodyMapView.FRONT) "거울을 보듯 화면 왼쪽이 내 몸의 왼쪽이에요." else " ",
                fontSize = 12.sp,
                color = InkFaint,
                modifier = Modifier.padding(top = 8.dp)
            )

            val map = bodyMaps[currentView]
            if (map == null) {
                NoteBox("바디맵 리소스를 불러오지 못했습니다.", modifier = Modifier.padding(top = 16.dp))
            } else {
                Canvas(
                    modifier = Modifier
                        .fillMaxWidth(0.62f)
                        .align(Alignment.CenterHorizontally)
                        .padding(vertical = 12.dp)
                        .aspectRatio(map.viewBoxWidth / map.viewBoxHeight)
                        .pointerInput(currentView) {
                            detectTapGestures { tap ->
                                val scale = min(
                                    size.width / map.viewBoxWidth,
                                    size.height / map.viewBoxHeight
                                )
                                val dx = (size.width - map.viewBoxWidth * scale) / 2f
                                val dy = (size.height - map.viewBoxHeight * scale) / 2f
                                val vx = (tap.x - dx) / scale
                                val vy = (tap.y - dy) / scale
                                // Top layer (arm) first; a tap outside its regions falls through.
                                map.layers.asReversed().firstNotNullOfOrNull { layer ->
                                    if (!polygonContains(layer.outline, vx, vy)) null
                                    else layer.regions.lastOrNull { polygonContains(it.points, vx, vy) }
                                }?.let { onRegionToggled(it.id) }
                            }
                        }
                ) {
                    val scale = min(
                        size.width / map.viewBoxWidth,
                        size.height / map.viewBoxHeight
                    )
                    val dx = (size.width - map.viewBoxWidth * scale) / 2f
                    val dy = (size.height - map.viewBoxHeight * scale) / 2f

                    withTransform({
                        translate(dx, dy)
                        scale(scale, scale, Offset.Zero)
                    }) {
                        fun drawLayer(layer: BodyLayer) {
                            drawPath(layer.outlinePath, color = baseColor)
                            layer.clippedPaths.forEach { (region, path) ->
                                if (region.id in selectedRegions) drawPath(path, color = selectedColor)
                            }
                            layer.clippedPaths.values.forEach { path ->
                                drawPath(path, color = seamColor, style = Stroke(width = 1.2f))
                            }
                            drawPath(layer.outlinePath, color = outlineColor, style = Stroke(width = 1.1f))
                        }
                        map.layers.firstOrNull()?.let { drawLayer(it) }
                        map.decorations.forEach { deco ->
                            val topLeft = Offset(deco.cx - deco.rx, deco.cy - deco.ry)
                            val ovalSize = Size(deco.rx * 2, deco.ry * 2)
                            drawOval(color = baseColor, topLeft = topLeft, size = ovalSize)
                            drawOval(
                                color = outlineColor, topLeft = topLeft, size = ovalSize,
                                style = Stroke(width = 1.1f)
                            )
                        }
                        map.layers.drop(1).forEach { drawLayer(it) }
                    }
                }
            }

            if (selectedRegions.isNotEmpty()) {
                SectionLabel("선택한 부위 · 탭하면 해제")
                FlowRow(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    selectedRegions.sorted().forEach { id ->
                        SelectPill(
                            text = HomecareDictionary.svgRegionLabel(id) + "  ×",
                            selected = true,
                            onClick = { onRegionToggled(id) }
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))
        }

        BottomActions {
            PrimaryButton(
                text = if (selectedRegions.isEmpty()) "건너뛰기" else "다음 (${selectedRegions.size}곳 선택)",
                onClick = onNext,
                modifier = Modifier.weight(1f)
            )
        }
    }
}
